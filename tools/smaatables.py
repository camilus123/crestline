#!/usr/bin/env python3
"""Makes src/render/smaatables.ts from the two lookup tables of the SMAA project.

    python3 tools/smaatables.py <folder with AreaTex.h and SearchTex.h>

The tables are the precomputed textures of SMAA (https://github.com/iryoku/smaa, Textures/AreaTex.h and
Textures/SearchTex.h, MIT licence: third_party/smaa/LICENSE.txt). They are stored unchanged in content: each
byte less the byte to its left and then less the byte above (which packs a third smaller), deflated, base64.
src/render/smaa.ts undoes that at start-up; tests/smaatables.test.ts checks the result against the hashes below.
"""
import base64, hashlib, pathlib, re, sys, zlib

AREA = (160, 560, 2)   # width, height, bytes per texel (RG)
SEARCH = (64, 16, 1)   # (R)


def load(path, dims):
    text = pathlib.Path(path).read_text()
    body = text[text.index('{') + 1:text.rindex('}')]
    data = bytes(int(x, 16) for x in re.findall(r'0x([0-9a-fA-F]{2})', body))
    assert len(data) == dims[0] * dims[1] * dims[2], (path, len(data))
    return data


def pack(data, dims):
    w, _, bpp = dims
    pitch = w * bpp
    left = bytearray(len(data))
    for i, b in enumerate(data):
        left[i] = (b - (data[i - bpp] if i % pitch >= bpp else 0)) & 255
    up = bytearray(len(data))
    for i, b in enumerate(left):
        up[i] = (b - (left[i - pitch] if i >= pitch else 0)) & 255
    c = zlib.compressobj(9, zlib.DEFLATED, -15)
    return base64.b64encode(c.compress(bytes(up)) + c.flush()).decode()


def main():
    src = pathlib.Path(sys.argv[1])
    area, search = load(src / 'AreaTex.h', AREA), load(src / 'SearchTex.h', SEARCH)
    out = pathlib.Path(__file__).resolve().parent.parent / 'src/render/smaatables.ts'
    out.write_text(
        '// GENERATED by tools/smaatables.py: do not edit.\n'
        '// The area and search lookup tables of SMAA (https://github.com/iryoku/smaa), unchanged in content.\n'
        '// Copyright (C) 2013 Jorge Jimenez, Jose I. Echevarria, Belen Masia, Fernando Navarro, Diego Gutierrez.\n'
        '// MIT licence: third_party/smaa/LICENSE.txt.\n'
        '// Packed: each byte less its left neighbour, then less the one above, deflated, base64.\n'
        f'export const AREA = {{ w: {AREA[0]}, h: {AREA[1]}, bpp: {AREA[2]}, sha256: \'{hashlib.sha256(area).hexdigest()}\' }};\n'
        f'export const SEARCH = {{ w: {SEARCH[0]}, h: {SEARCH[1]}, bpp: {SEARCH[2]}, sha256: \'{hashlib.sha256(search).hexdigest()}\' }};\n'
        f'export const AREA_Z = \'{pack(area, AREA)}\';\n'
        f'export const SEARCH_Z = \'{pack(search, SEARCH)}\';\n')
    print(f'wrote {out}  ({out.stat().st_size} bytes)')


if __name__ == '__main__':
    main()
